#!/usr/bin/env python3
"""Builds src/lib/visualizer/translations/<name>.ts from scripts/translations/src/<name>.txt

Source format (one block per problem):

  ## problem-id            (or  ## example:some-id)
  @python | @java | @cpp   (a section per language)
  <one entry per JavaScript line, in order>

Entries:
  code        this line stands for the next JS line
  .           the next JS line has no line in this language (e.g. a lone "}")
  _           the next JS line is blank -> blank line here
  ~ code      extra line that is not a JS line (imports, class wrapper...). "~" alone = blank extra line
  ~M          start of main(): Java / C++ main wrapper is written for you, and closed at the end

Indent is automatic for Java (class body = 4 spaces, main body = 8) and C++ (main body = 4).
Run:  node node_modules/.pnpm/tsx@*/node_modules/tsx/dist/cli.mjs scripts/translations/dump-js.ts /tmp/js-code.json
      python3 scripts/translations/build.py
"""
import json, re, sys, pathlib

root = pathlib.Path(__file__).resolve().parents[2]
js = json.load(open("/tmp/js-code.json"))
HEAD = {
    "java": ["-|import java.util.*;", "-|", "-|public class Main {"],
    "cpp": ["-|#include <bits/stdc++.h>", "-|using namespace std;", "-|"],
}

def render(key, lang, body, nlines):
    jsl = js[key].split("\n")
    out, n, in_main = list(HEAD.get(lang, [])), 0, False
    def ind():
        if lang == "java": return " " * (8 if in_main else 4)
        if lang == "cpp": return " " * (4 if in_main else 0)
        return ""
    for raw in body:
        s = raw.rstrip()
        if s == "~M":
            if lang == "java": out.append("-|    public static void main(String[] args) {")
            elif lang == "cpp": out.append("-|int main() {")
            in_main = True; continue
        if s.startswith("~"):
            t = s[1:].lstrip(" ") if s.strip() != "~" else ""
            out.append("-|" + (ind() + t if t else "")); continue
        n += 1
        t = jsl[n - 1].strip() if n <= len(jsl) else ""
        kind = "." if s.strip() == "." else "_" if s.strip() == "_" else "code"
        if kind == "." and not t.startswith("}"): raise SystemExit(f"{key} [{lang}] entry {n}: '.' but JS line is {t!r}")
        if kind == "_" and t != "": raise SystemExit(f"{key} [{lang}] entry {n}: '_' but JS line is {t!r}")
        if kind == "code" and t == "": raise SystemExit(f"{key} [{lang}] entry {n}: code but JS line is blank")
        if s.strip() == ".": continue
        if s.strip() == "_": out.append(f"{n}|"); continue
        out.append(f"{n}|{ind()}{s}")
    if n != nlines: raise SystemExit(f"{key} [{lang}]: {n} entries but the JS has {nlines} lines")
    if lang == "java": out += (["-|    }"] if in_main else []) + ["-|}"]
    elif lang == "cpp" and in_main: out.append("-|}")
    return "\n".join(out)

def parse(text):
    blocks, cur, lang = {}, None, None
    for line in text.split("\n"):
        if line.startswith("## "): cur = line[3:].strip(); blocks[cur] = {}; lang = None; continue
        m = re.match(r"^@(python|java|cpp)\s*$", line)
        if m and cur: lang = m.group(1); blocks[cur][lang] = []; continue
        if cur and lang is not None: blocks[cur][lang].append(line)
    # trim trailing blank entries a text editor leaves between blocks
    for b in blocks.values():
        for l in b.values():
            while l and l[-1].strip() == "": l.pop()
    return blocks

for src in sorted((root / "scripts/translations/src").glob("*.txt")):
    blocks = parse(src.read_text())
    ts = ['import type { TranslationSet } from "./index";', "", f"/** Generated by scripts/translations/build.py from src/{src.name}. Do not edit by hand. */",
          f"export const {src.stem.upper().replace('-', '_')}_TRANSLATIONS: Record<string, TranslationSet> = {{"]
    for key, langs in blocks.items():
        if key not in js: raise SystemExit(f"unknown key {key}")
        nl = len(js[key].split("\n"))
        ts.append(f'  "{key}": {{')
        for lang, body in langs.items():
            r = render(key, lang, body, nl)
            assert "`" not in r and "${" not in r, key
            ts.append(f"    {lang}: `\n{r}\n`,")
        ts.append("  },")
    ts.append("};\n")
    (root / "src/lib/visualizer/translations" / f"{src.stem}.ts").write_text("\n".join(ts))
    print(src.stem, len(blocks), "problems")
